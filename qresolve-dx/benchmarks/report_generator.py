"""
QResolve-Dx: Benchmark Report Generator

Generates a comprehensive benchmark report comparing:
  1. Classical XGBoost performance (overall and per-class)
  2. Hard-case detection statistics
  3. Quantum kernel SVM vs Classical RBF-SVM on hard cases
  4. McNemar's statistical significance test
  5. Honest disclosure of synthetic data limitations

All results include proper statistical context — no bare accuracy
deltas without significance tests on small samples.
"""

from __future__ import annotations

import sys
import os
import json
from datetime import datetime
from typing import Dict, Optional

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

from data.disease_data import DISEASE_NAMES, LABEL_DISEASE_MAP, NUM_CLASSES


def generate_report(
    cv_results: Dict,
    calibration_metrics: Dict,
    confusion_analysis: Dict,
    quantum_benchmark: Optional[Dict] = None,
) -> str:
    """
    Generate the full benchmark report as markdown.

    Args:
        cv_results: From train_xgb.train_with_cv()
        calibration_metrics: From calibrate.calibrate_model()
        confusion_analysis: From detector.analyze_confusion_distribution()
        quantum_benchmark: From benchmark_classical_svm.benchmark_quantum_vs_classical()
                          (None if quantum pipeline was not run)

    Returns:
        Markdown-formatted report string
    """
    report = []
    report.append("# QResolve-Dx Benchmark Report")
    report.append(f"\n**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    report.append(f"**Diseases:** {', '.join(DISEASE_NAMES)}")
    report.append("")

    # --- Disclaimer ---
    report.append("## ⚠️ Data Disclosure")
    report.append("")
    report.append("> **IMPORTANT:** All results in this report are on **synthetic data**")
    report.append("> generated by sampling HPO terms from published annotation-frequency")
    report.append("> distributions for each disease. No real Marfan-cluster patient dataset")
    report.append("> exists at usable scale for ML training. This is standard practice for")
    report.append("> rare disease research, but results should not be interpreted as")
    report.append("> clinical validation. See §10 of the build brief for known risks.")
    report.append("")

    # --- Classical Pipeline ---
    report.append("## 1. Classical Pipeline (XGBoost)")
    report.append("")
    report.append(f"- **Cross-validation:** Stratified {cv_results.get('n_splits', 5)}-fold")
    report.append(f"- **Overall Accuracy (OOF):** {cv_results.get('overall_accuracy', 0):.4f}")
    report.append(f"- **Overall Macro-F1 (OOF):** {cv_results.get('overall_macro_f1', 0):.4f}")
    report.append(f"- **Overall Log-Loss (OOF):** {cv_results.get('overall_log_loss', 0):.4f}")
    report.append("")

    # Per-fold results
    if 'folds' in cv_results:
        report.append("### Per-Fold Results")
        report.append("")
        report.append("| Fold | Accuracy | Macro-F1 | Log-Loss |")
        report.append("|------|----------|----------|----------|")
        for fold in cv_results['folds']:
            report.append(
                f"| {fold['fold']} | {fold['accuracy']:.4f} | "
                f"{fold['macro_f1']:.4f} | {fold['log_loss']:.4f} |"
            )
        report.append("")

    # Confusion matrix
    if 'confusion_matrix' in cv_results:
        report.append("### Confusion Matrix")
        report.append("")
        cm = cv_results['confusion_matrix']
        header = "| | " + " | ".join(
            LABEL_DISEASE_MAP.get(i, f"Class {i}")[:12] for i in range(len(cm))
        ) + " |"
        report.append(header)
        report.append("|" + "---|" * (len(cm) + 1))
        for i, row in enumerate(cm):
            name = LABEL_DISEASE_MAP.get(i, f"Class {i}")[:12]
            vals = " | ".join(str(v) for v in row)
            report.append(f"| **{name}** | {vals} |")
        report.append("")

    # --- Calibration ---
    report.append("## 2. Probability Calibration")
    report.append("")
    report.append(f"- **Method:** {calibration_metrics.get('method', 'isotonic')}")
    report.append(f"- **Uncalibrated Log-Loss:** {calibration_metrics.get('uncalibrated_log_loss', 0):.4f}")
    report.append(f"- **Calibrated Log-Loss:** {calibration_metrics.get('calibrated_log_loss', 0):.4f}")

    improvement = (calibration_metrics.get('uncalibrated_log_loss', 0) -
                   calibration_metrics.get('calibrated_log_loss', 0))
    report.append(f"- **Improvement:** {improvement:+.4f}")
    report.append("")

    if 'per_class' in calibration_metrics:
        report.append("### Per-Class Brier Scores")
        report.append("")
        report.append("| Disease | Uncalibrated | Calibrated | Improved? |")
        report.append("|---------|-------------|------------|-----------|")
        for cls_name, scores in calibration_metrics['per_class'].items():
            improved = "✓" if scores['brier_calibrated'] < scores['brier_uncalibrated'] else "—"
            report.append(
                f"| {cls_name[:25]} | {scores['brier_uncalibrated']:.4f} | "
                f"{scores['brier_calibrated']:.4f} | {improved} |"
            )
        report.append("")

    # --- Confusion Detection ---
    report.append("## 3. Confusion Detection")
    report.append("")
    report.append(f"- **Total cases:** {confusion_analysis.get('n_total', 0)}")
    report.append(f"- **Hard cases:** {confusion_analysis.get('n_hard', 0)} "
                  f"({confusion_analysis.get('hard_rate', 0):.1%})")
    report.append(f"- **Easy cases:** {confusion_analysis.get('n_easy', 0)}")
    report.append(f"- **Margin τ:** {confusion_analysis.get('margin_tau', 0):.3f}")
    report.append(f"- **Entropy τ:** {confusion_analysis.get('entropy_tau', 0):.3f}")
    report.append(f"- **Hard-case accuracy (before quantum):** "
                  f"{confusion_analysis.get('hard_case_accuracy', 0):.4f}")
    report.append(f"- **Easy-case accuracy:** "
                  f"{confusion_analysis.get('easy_case_accuracy', 0):.4f}")
    report.append("")

    if 'trigger_breakdown' in confusion_analysis:
        report.append("### Trigger Breakdown")
        report.append("")
        for trigger, count in confusion_analysis['trigger_breakdown'].items():
            report.append(f"- **{trigger}:** {count}")
        report.append("")

    if 'top_confusion_pairs' in confusion_analysis:
        report.append("### Most Confused Disease Pairs")
        report.append("")
        report.append("| Pair | Count |")
        report.append("|------|-------|")
        for pair, count in list(confusion_analysis['top_confusion_pairs'].items())[:5]:
            report.append(f"| {pair} | {count} |")
        report.append("")

    # --- Quantum vs Classical ---
    if quantum_benchmark:
        report.append("## 4. Quantum Kernel SVM vs Classical RBF-SVM")
        report.append("")
        report.append("> This comparison is on the **hard-case subset only** — the cases")
        report.append("> where the classical XGBoost triage model was uncertain.")
        report.append("")

        n_test = quantum_benchmark.get('n_test', 0)
        report.append(f"- **Hard-case test set size:** n = {n_test}")
        report.append("")

        report.append("| Metric | Quantum QSVM | Classical RBF-SVM |")
        report.append("|--------|-------------|-------------------|")
        q_acc = quantum_benchmark.get('quantum_accuracy', 0)
        c_acc = quantum_benchmark.get('classical_accuracy', 0)
        q_f1 = quantum_benchmark.get('quantum_f1', 0)
        c_f1 = quantum_benchmark.get('classical_f1', 0)
        report.append(f"| Accuracy | {q_acc:.4f} | {c_acc:.4f} |")
        report.append(f"| Macro-F1 | {q_f1:.4f} | {c_f1:.4f} |")
        report.append("")

        p_value = quantum_benchmark.get('mcnemar_p_value', None)
        conclusion = quantum_benchmark.get('conclusion', 'No test performed')

        report.append("### Statistical Significance (McNemar's Test)")
        report.append("")
        if p_value is not None:
            report.append(f"- **McNemar's p-value:** {p_value:.4f}")
            report.append(f"- **Significance level:** α = 0.05")
            report.append(f"- **Conclusion:** {conclusion}")
        else:
            report.append("- McNemar's test could not be performed (insufficient data)")
        report.append("")

        report.append("> **Note on small sample sizes:** Given the likely small n of hard")
        report.append(f"> cases (n = {n_test}), any accuracy delta must be interpreted with")
        report.append("> caution. McNemar's test is appropriate for paired comparisons on")
        report.append("> small samples, but statistical power is limited. An unqualified")
        report.append("> 'quantum won by X%' claim without this context would be misleading.")
        report.append("")
    else:
        report.append("## 4. Quantum Resolver")
        report.append("")
        report.append("Quantum pipeline was not run. Classical results only.")
        report.append("")

    # --- Summary ---
    report.append("## 5. Summary")
    report.append("")
    report.append("| Component | Status | Key Metric |")
    report.append("|-----------|--------|------------|")
    report.append(f"| Classical XGBoost | ✓ | F1 = {cv_results.get('overall_macro_f1', 0):.4f} |")
    report.append(f"| Calibration | ✓ | ΔLogLoss = {improvement:+.4f} |")
    report.append(f"| Confusion Detection | ✓ | {confusion_analysis.get('hard_rate', 0):.1%} hard |")
    if quantum_benchmark:
        report.append(f"| Quantum QSVM | ✓ | F1 = {quantum_benchmark.get('quantum_f1', 0):.4f} |")
        report.append(f"| McNemar's Test | ✓ | p = {quantum_benchmark.get('mcnemar_p_value', 'N/A')} |")
    else:
        report.append("| Quantum QSVM | ✗ | Not run |")
    report.append("")

    return "\n".join(report)


def save_report(report_text: str, output_dir: str) -> str:
    """Save report as markdown and return the path."""
    os.makedirs(output_dir, exist_ok=True)
    path = os.path.join(output_dir, "benchmark_report.md")
    with open(path, 'w', encoding='utf-8') as f:
        f.write(report_text)
    print(f"\n  Benchmark report saved to: {path}")
    return path


def save_metrics_json(
    cv_results: Dict,
    calibration_metrics: Dict,
    confusion_analysis: Dict,
    quantum_benchmark: Optional[Dict],
    output_dir: str,
) -> str:
    """Save all metrics as JSON for programmatic access."""
    os.makedirs(output_dir, exist_ok=True)

    # Clean numpy arrays for JSON serialization
    def clean(obj):
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, (np.floating,)):
            return float(obj)
        if isinstance(obj, dict):
            return {k: clean(v) for k, v in obj.items()}
        if isinstance(obj, (list, tuple)):
            return [clean(v) for v in obj]
        return obj

    metrics = {
        "generated": datetime.now().isoformat(),
        "classical_cv": clean({k: v for k, v in cv_results.items()
                               if k != 'oof_predictions'}),
        "calibration": clean(calibration_metrics),
        "confusion_detection": clean(confusion_analysis),
        "quantum_benchmark": clean(quantum_benchmark) if quantum_benchmark else None,
    }

    path = os.path.join(output_dir, "benchmark_metrics.json")
    with open(path, 'w') as f:
        json.dump(metrics, f, indent=2, default=str)
    print(f"  Metrics JSON saved to: {path}")
    return path


